class AgroChatbotView(APIView):
    """
    POST /api/chat/
    Accepts:
      - message: str (user query)
      - history: list (optional previous turns)
      - language: 'en' | 'ml'
    Returns AI response generated by Google Gemini with agronomic context.
    """
    permission_classes = [AllowAny]

    def post(self, request):
        message = request.data.get("message", "").strip()
        history = request.data.get("history", [])
        language = request.data.get("language", "en").strip().lower()

        if not message:
            return Response(
                {"status": "error", "message": "Message content cannot be empty."},
                status=status.HTTP_400_BAD_REQUEST
            )

        try:
            rag_result = query_gemini_chat_with_rag(message=message, history=history, language=language)

            return Response({
                "status": "success",
                "reply": rag_result.get("reply", ""),
                "sources": rag_result.get("sources", []),
                "grounded_by_rag": rag_result.get("grounded_by_rag", True),
                "model": rag_result.get("model", "gemini-1.5-flash"),
                "timestamp": datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S UTC"),
                "language": language
            }, status=status.HTTP_200_OK)

        except Exception as e:
            return Response({
                "status": "error",
                "message": f"Chatbot processing error: {str(e)}"
            }, status=status.HTTP_500_INTERNAL_SERVER_ERROR)


class AgroChatSuggestionsView(APIView):
    """
    GET /api/chat/suggestions/?language=en|ml
    Returns curated quick suggestion prompts for farmers.
    """
    permission_classes = [AllowAny]

    def get(self, request):
        language = request.query_params.get("language", "en").strip().lower()
        if language not in ("en", "ml"):
            language = "en"

        return Response({
            "status": "success",
            "language": language,
            "suggestions": SUGGESTIONS.get(language, SUGGESTIONS["en"])
        }, status=status.HTTP_200_OK)
